-- 봇이 "지금 이 방으로 보낼 수 있다" 를 서버에 알려주는 자리
--
-- 왜 필요한가: 서버는 카톡에 직접 말할 수 없고, 실제로 글을 넣는 것은 봇 단말이 들고 있는
-- 알림 답장 통로(RemoteInput)뿐이다. 그 통로는 그 방 알림이 한 번 와야 열리고, 앱이 죽거나
-- 폰이 재부팅되면 전멸한다(PendingIntent 는 프로세스 토큰이다).
--
-- 그래서 조용한 방(마지막 수신이 며칠 전)에 대시보드로 글을 쓰면 9초 만에 3회 실패로 죽는다.
-- 실측 2026-08-31: 행정114테크 방, 마지막 수신 8/25, 09:25:41·45·50 세 번에 failed.
-- 사람은 "보내기" 를 누르는 순간까지 그걸 알 방법이 없었다 — 업무 카톡에서 제일 나쁜
-- "보낸 줄 알았는데 안 갔다" 가 정확히 이 모양으로 난다.
--
-- 봇은 이미 1분마다 outbox 를 두드리고, 그때 자기 통로 목록을 알고 있다(allowedReplyRooms).
-- 그 목록을 심장박동에 한 줄 얹으면 화면이 **쓰기 전에** 막아줄 수 있다.
--
-- 담기는 값은 **규칙 pattern** 이다(예: '방#475980158535455'). 화면에 보이는 방 이름이
-- 아니다 — 봇이 아는 이름은 그쪽이고, claimOutbound 가 내려보내는 것도 그쪽이다.
alter table kakao_bot_status
  add column if not exists sendable_rooms text[],
  -- 목록을 마지막으로 받은 시각. 이 값이 오래됐으면 "닫혔다" 가 아니라 "모른다" 다 —
  -- 봇이 죽었거나 구버전 스크립트라 목록을 안 올리는 것이고, 그때 "못 보낸다" 고
  -- 단정하면 멀쩡한 방에 거짓 경고가 뜬다. 거짓 경보는 경보가 없느니만 못하다.
  add column if not exists sendable_at timestamptz;
